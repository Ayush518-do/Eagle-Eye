"""Safe file storage for uploads.

The file type is decided from the file's first bytes (its "magic number"), not from the
name the user gave it, so `virus.exe` renamed to `photo.jpg` is rejected.
"""
import hashlib
import re
import uuid
from pathlib import Path, PurePosixPath, PureWindowsPath

# first bytes -> (canonical content type, extension we save with)
_SIGNATURES: list[tuple[bytes, str, str]] = [
    (b"\xff\xd8\xff", "image/jpeg", ".jpg"),
    (b"\x89PNG\r\n\x1a\n", "image/png", ".png"),
    (b"%PDF-", "application/pdf", ".pdf"),
]


class UploadRejected(ValueError):
    """Raised with a message that is safe to show to the user."""


def detect_type(head: bytes) -> tuple[str, str]:
    for sig, ctype, ext in _SIGNATURES:
        if head.startswith(sig):
            return ctype, ext
    raise UploadRejected("Unsupported file type. Allowed: JPEG, PNG, PDF.")


def save_upload(data: bytes, original_name: str, upload_dir: Path, max_mb: int) -> dict:
    if not data:
        raise UploadRejected("The file is empty.")
    if len(data) > max_mb * 1024 * 1024:
        raise UploadRejected(f"File is larger than the {max_mb} MB limit.")
    ctype, ext = detect_type(data[:16])

    file_id = uuid.uuid4().hex
    upload_dir.mkdir(parents=True, exist_ok=True)
    # The stored name is generated by us; the user's name is kept only as metadata,
    # so names like "../../etc/passwd" can never choose where the file is written.
    (upload_dir / f"{file_id}{ext}").write_bytes(data)

    return {
        "file_id": file_id,
        "original_name": PureWindowsPath(PurePosixPath(original_name or "upload").name).name[:200],
        "content_type": ctype,
        "size_bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
    }


_STORED_ID = re.compile(r"^[0-9a-f]{32}$")
_MEDIA_TYPES = {".jpg": "image/jpeg", ".png": "image/png", ".pdf": "application/pdf"}


def find_upload(upload_dir: Path, file_id: str) -> tuple[Path, str] | None:
    """The stored file for an id we generated, with its content type; None if it is not there.
    Ids that are not 32 hex characters are never turned into a path."""
    if not _STORED_ID.match(file_id):
        return None
    for ext, media_type in _MEDIA_TYPES.items():
        path = upload_dir / f"{file_id}{ext}"
        if path.is_file():
            return path, media_type
    return None


def remove_upload(upload_dir: Path, file_id: str) -> None:
    """Delete a file we just saved, used when the database write that follows it fails."""
    found = find_upload(upload_dir, file_id)
    if found:
        found[0].unlink(missing_ok=True)
